def main() -> None:
    rows = _collect()
    _write_inventory(rows)
    _write_glossary()
    print(f"Generated: {INVENTORY_MD.relative_to(ROOT)}")
    print(f"Generated: {GLOSSARY_MD.relative_to(ROOT)}")
    print(f"Conditions processed: {len(rows)}")


if __name__ == "__main__":
    main()
