            "- KO: 불필요한 영문 음차(예: 리턴)는 가능하면 한국 투자자 표준 용어(수익률)로 통일.",
            "- ZH: 回报率/收益率가 혼재될 경우 기본은 收益率, 맥락상 성과 총괄은 回报可容.",
